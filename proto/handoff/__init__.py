#: 没有第二种排法，也就没有"两套"可失配。


# ──────────────────────────── 排版 ────────────────────────────

#: **段体缩进** —— 段名在 0 列，段体一律在 2 列，每下一层再 +2。
#:
#: 🔴 用户 2026-11-03：*"缩进排版也有问题"*。原来是"哪段想缩才缩"，实测三种破法：
#:
#:   ① 多行的「答」**续行掉到 0 列**，整块脱出所在段落（只给「问」缩了，没给「答」缩）；
#:   ② 「答」那一行和「问」的续行**同一个缩进** → 答看起来像问的一部分；
#:   ③ 被点名那几轮的原文在 0 列，跟它上面那个 `-` 对不齐
#:      （⚠️ 这条**已随"点名"一起消失**，2026-11-03 —— 用户原话现在只有**索引**一种形状，
#:      见 `briefing.turn_lines`。规矩不变，只是再也没有"第二种形状"可对不齐）。
#:
#: 一条规矩治三种：**段名 0 列 · 段体 2 列 · 每层 +2**。
#:
#: ⚠️ 定义放这里、不放各跳自己家里，是用户 2026-11-03 的另一条：
#: *"任何涉及交接的地方你都不要搞两套 —— 你显示给我看的，就是传给 llm 看的"*。
#: 排版是**所有交接点共用的一条规矩**，所以它属于共享词汇表。
BODY = "  "


def body_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**多行值**整块缩进 —— 每一行都缩。

    ⚠️ **空行也留缩进**（留成 `pad`）：留成空串的话，块被空行切断 ——
    上面那行是列表项时，markdown 里后面几行就散到块外面去了。
    """
    raw = str(text or "")
    if not raw.strip():
        return []
    return [f"{pad}{ln}" if ln.strip() else pad for ln in raw.splitlines()]


def bullet_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**可能多行**的列表项 —— 首行带 `- `，续行对齐到**文字**，不顶回 0 列。"""
    ls = str(text or "").splitlines() or [""]
    return [f"{pad}- {ls[0]}", *(f"{pad}  {ln}" for ln in ls[1:])]


