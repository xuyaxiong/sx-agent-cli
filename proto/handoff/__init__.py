#:
#: 它当年解决的是"短模板要不要和段名同行"。但**同行就是"两套排版"**：
#: 段名和段体挤在一行，读的人分不清哪儿是标题、哪儿是正文（用户原话：
#: *"仿佛是同一个层级"*）。现在只有**一条规矩** ——
