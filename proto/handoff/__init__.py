#: 段名和段体挤在一行，读的人分不清哪儿是标题、哪儿是正文（用户原话：
#: *"仿佛是同一个层级"*）。现在只有**一条规矩** ——
#: **段名独占一行 → 来源另起一行 → 段体缩进 2 列**（`section_head` ＋ `body_lines`）。
#: 没有第二种排法，也就没有"两套"可失配。


def body_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**多行值**整块缩进 —— 每一行都缩。

    ⚠️ **空行也留缩进**（留成 `pad`）：留成空串的话，块被空行切断 ——
    上面那行是列表项时，markdown 里后面几行就散到块外面去了。
    """
    raw = str(text or "")
    if not raw.strip():
        return []
    return [f"{pad}{ln}" if ln.strip() else pad for ln in raw.splitlines()]


def bullet_lines(text: object, pad: str = BODY) -> list[str]:
    """一个**可能多行**的列表项 —— 首行带 `- `，续行对齐到**文字**，不顶回 0 列。"""
    ls = str(text or "").splitlines() or [""]
    return [f"{pad}- {ls[0]}", *(f"{pad}  {ln}" for ln in ls[1:])]


