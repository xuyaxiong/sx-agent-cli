#:
#: ⚠️ 段名一律是 `【…】` 形式、**独占行首** —— 记录层靠这两条做确定性切分。
SECTION: dict[str, str] = {
    # ── 委托单（平台 → 执行器，`briefing.py`）──
    "task": "【任务】",
    "user_turns": "【用户原话】",
    # ⚠️ 2026-11-03 改名：原来叫【你上次说到哪】，里面**混着两方的话**
    # （判定的 progress/missing ＋ 执行器自己的 report）。现在 `report` 挪进
    # 【问答经过】按时间序排，这一段**只剩判定的话** —— 段名跟着变成"判定"。
    # ⚠️ 2026-11-03 改名：原来叫【已经答复过的信息】，但它现在也承载
    # "**它最后说的那句**"（可能还没人答）—— 旧名字在那条上就是**假话**。
    "answered": "【问答经过】",
    "already_produced": "【已经产出的产物】",
    "readable": "【可读产物】",
    "resume": "【续跑提示】",
    # ── 回执（执行器 → 主 agent，`receipt.py`）──
    "deliver": "【交付】",
    "produced": "【产出的产物】",
    "report": "【执行器说】",
    "agent_answer": "【你补的信息】",
    "next": "【下一步】",
    #: 平台故障（`receipt.py`）：这一轮**根本没跑成** —— 与"执行器没干成"是两回事，
    #: 所以**单起一段**，不塞进【执行器说】（那句话的来源标注是"它说的"）。
    "fault": "【平台故障】",
    # ── 派发被拒（平台 → 主 agent，**不建 Task**）──
    "not_dispatched": "【这次没有派发】",
    "available_skills": "【可用的能力】",
    "available_artifacts": "【本会话现有产物】",
}

#: **来源标注** —— "这句是谁说的"。**两个交接点共用这一份**。
#:
#: 🔴 它**属于结构**，不是措辞装饰：记录层切段时要**原样剥掉**它，剩下的才是内容。
#: 没有这张表就只能靠"行首是 `（…）` 就剥"这种启发式 —— 而 `（无）` 这种**真内容**
#: 会被误剥（2026-11-03 实测踩到：派发被拒那条回执切出来少了一段）。
#:
#: ⚠️ **不带外层括号**（2026-11-03）：它现在渲染在 `来源：` 后面、**独占一行** ——
#: 带括号的话读起来是"标题的附注"，正是要治的那个毛病。
SOURCE_NOTE: dict[str, str] = {
    # ── 委托单（`briefing.py`）──
    "task": "**主 agent 交代的** —— 它根据对话写的，可能补了用户没说的东西",
    "user_turns": "**用户说的** —— 平台直接搬，未经转述",
    "answered": "**按时间顺序**，新的在下 —— 一问一答成对，免得「答」脱离了「问」",
    # ── 回执（`receipt.py`）──
    "report": "**它说的** —— 原样，未经改写",
    "agent_answer": "**你说的** —— 已成对记进 Task，下次重入还会带上",
    "fault": "**平台说的** —— 不是执行器说的",
}

#: 来源那一行的前缀 —— `来源：` 后面接 `SOURCE_NOTE[key]`。
SOURCE_LABEL = "来源："


# ──────────────────────────── 状态词汇 ────────────────────────────
#
# 🔴 **为什么收在这里**（2026-11-04 复审 N4）：同一套状态原来在**四处**各写一遍字符串
# （`executor.OutcomeStatus` · `briefing._STATUS_TO_STAGE`
# 的键 · `ledger.STAGE_MARK` 的键）—— `settle()` 收敛的是**写法**，**词汇**还靠人守同名：
# 改一处状态名，其余三处**静默分叉**。这正是 `registry` 在技能表上刚治过的病的翻版。
# 词汇表本来就是本模块的职责（段名 / 来源标注 / 出口分类都在这），状态名一并在这一份里。
#
# ⚠️ 覆盖性由 `unit_handoff` 的守卫盯着（三态 ↔ 映射键、五态 ↔ `STAGE_MARK` 键），
#    不是靠"记得改另外三处"。

#: **执行器三态** —— `ExecOutcome.status` 用的就是它。⚠️ 2026-11-05 起它**由平台按结构算**
#: （申报要信息 / 交了产物 / 都没有），**不是**某次 LLM 调用的结论（判定已退休）。
OutcomeStatus = Literal["completed", "waiting_for_input", "incomplete"]

#: **Task 五态** —— 台账 / 展示用的任务状态机（`Task.stage`）。
#: 与三态**前三个同名**；唯一的映射是 `incomplete → failed`（判定说"还没做完"，
#: 推满轮次后任务记"失败"）。另两个（`running` / `superseded`）不在三态里：
#: 一个是"刚建、还没跑完"，一个是"同技能被重新委派、不用管了"。
TaskStage = Literal["running", "completed", "waiting_for_input", "failed", "superseded"]


def section_head(key: str) -> list[str]:
    """**段名独占一行** ＋（有来源的话）**来源另起一行** —— 两个交接点共用这一条。

    🔴 用户 2026-11-03 在三选一里挑的排法（原话：*"仿佛是同一个层级"*）。
    改之前段名后面直接跟一长串括号说明（`【任务】（**主 agent 交代的** —— …）`），
    段体只缩 2 格 —— 两行看着**像同一个层级**，标题不像标题。

    现在：**段名 0 列 → 来源 2 列 → 段体 2 列**。段体由调用方接（`body_lines`）。
    """
    out = [SECTION[key]]
    note = SOURCE_NOTE.get(key)
    if note:
        out.append(f"{BODY}{SOURCE_LABEL}{note}")
    return out


