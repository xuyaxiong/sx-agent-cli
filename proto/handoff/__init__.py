def render_hop(hop: str, sections: dict[str, str]) -> str:
    """**所有交接单的唯一渲染入口** —— 段名 / 来源 / 缩进 / 顺序全由词汇表定。

    🔴 **为什么要收敛到一处**（用户 2026-11-05）：*"这些统一都要有个统一的处理，
    不是随便想写啥就写啥 —— 比如决策单长什么样、委托单长什么样，
    都应该从**形式上**确定下来。"*

    收敛之前，台账 / 试答 / 推回去 / 透传 **各拼各的字符串**，于是：

    | 违反 | 长什么样 |
    |---|---|
    | 段名后面直接跟内容 | 台账的 `【平台提示】你已委派出去的工作…` |
    | 段名不在词汇表里 | 台账的 `【平台提示】`、透传的 `【lesson-prep】` |
    | 续行缩进不是 2 的倍数 | 台账的 **6 格** |
    | 根本没有段名 | 试答整张（`HumanMessage:` 这种框架类型名直接漏给模型） |

    现在**渲染只有这一条路**：段名从 `SECTION` 取、来源从 `SOURCE_NOTE` 取、
    顺序从 `HOPS[hop]` 取、缩进用 `BODY`。**没有第二种写法，也就没有"两套"可失配。**

    ⚠️ **有内容才渲染** —— `sections` 里没给的段直接跳过（回执的段本来就是有条件的：
    有产物才出【产出的产物】）。"声明了却一次都没渲染过"由守卫盯着（没死段）。

    ⚠️ `hop` 没声明过就 **`KeyError`** —— 不静默降级（漏登记一个跳名要当场炸，
    而不是渲染出一张没有段名的单子）。
    """
    lines: list[str] = []
    for key in HOPS[hop]:
        text = str(sections.get(key) or "").strip()
        if not text:
            continue
        lines += section_head(key) + body_lines(text, BODY)
    return "\n".join(lines)
