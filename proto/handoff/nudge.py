"""**推回去**（平台 → 执行器）：这一轮**既没交东西、也没申报要信息**时，喂回去让它接着干。

## 这个文件是什么

一段模板：执行器"跑完了但什么都没给"时，平台把这段话喂回去让它接着干 ——
经 `render_hop("nudge", …)` 渲染成【平台要求】。

## 设计原则（不变量）

1. **只说平台看得见的两件事实** —— **没交产物**（`write_artifact` 这一轮没调过 ✓）、
   **没申报要信息**（`ask_user` 没调过 ✓）。平台**不读正文**，也就没有别的可说的。〔沿革 1〕
2. **点明两条出路**（交付 / 用 `ask_user` 说清缺什么）—— 这正是"平台造路"：
   不去猜它想说什么，而是把**正确的路**摆在它面前。
3. **渲染走唯一那条渲染路**（`render_hop`）〔沿革 2〕。

## 沿革（改过什么、为什么改）

> 编号是**引用锚**（正文里写 `〔沿革 N〕`）—— **只追加、不改号**，新条目加在**末尾**。

1. **判定退休，这段跟着改**（2026-11-05）。原来带的是**判定吐的** `progress` / `missing` ——
   "你已经完成了什么、还缺什么" ✗。判定那次调用整个没了，平台**不读正文**，
   也就**没有这个信息** ✓ 别在这里编。
2. **走唯一那条渲染路**（2026-11-05）。原来它是**裸拼的字符串**：没有段名、没有缩进，
   和交接书/回执**不是一套体例**。用户原话：
   *"这些统一都要有个统一的处理，不是随便想写啥就写啥。"*
"""

from __future__ import annotations

from proto.handoff import render_hop


def nudge_text() -> str:
    """**推它继续**时说什么 —— 只说平台看得见的两件事实 ＋ 两条出路。

    ⚠️ **走唯一那条渲染路**（`render_hop`）—— 原来是裸拼的字符串。〔沿革 2〕
    """
    return render_hop("nudge", {"nudge": "\n".join([
        "这一轮**既没有交付产物，也没有说明你需要什么信息**。",
        "",
        "两条路，选一条走：",
        "",
        "- **干完了** → 用 `write_artifact` 把成果**交付成产物**"
        "（正文写在回复里平台看不到，不算交付）；",
        "- **缺信息、干不下去** → 用 `ask_user` **说清缺什么**"
        "（平台会先问主 agent，它答不上再转用户）。",
        "",
        "不要用「已完成」这类话收尾 —— 那句话不构成交付。",
    ])})
