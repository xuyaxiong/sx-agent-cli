"""**推回去**（平台 → 执行器）：这一轮**既没交东西、也没申报要信息**时，喂回去让它接着干。

🔴 2026-11-05（判定退休）：这段原来带的是**判定吐的** `progress` / `missing` ——
   "你已经完成了什么、还缺什么" ✗。判定那次调用整个没了，平台**不读正文**，
   也就**没有这个信息** ✓ 别在这里编。

现在能说的只有平台**自己看得见的两件事实**：
  - **没交产物**（`write_artifact` 这一轮没调过 ✓）
  - **没申报要信息**（`ask_user` 没调过 ✓）

所以这段照着这两件说，并**点明两条出路**（交付 / 用 `ask_user` 说清缺什么）——
这正是"平台造路"：不去猜它想说什么，而是把**正确的路**摆在它面前。
"""

from __future__ import annotations


def nudge_text() -> str:
    """**推它继续**时说什么 —— 只说平台看得见的两件事实 ＋ 两条出路。"""
    return "\n\n".join([
        "这一轮**既没有交付产物，也没有说明你需要什么信息**。",
        "两条路，选一条走：",
        "- **干完了** → 用 `write_artifact` 把成果**交付成产物**"
        "（正文写在回复里平台看不到，不算交付）；",
        "- **缺信息、干不下去** → 用 `ask_user` **说清缺什么**"
        "（平台会先问主 agent，它答不上再转用户）。",
        "不要用「已完成」这类话收尾 —— 那句话不构成交付。",
    ])
