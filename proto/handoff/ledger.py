"""**台账**（平台 → 主 agent）：每轮开头把"派过什么、干到哪了"摆到它面前。

## 这个文件是什么

主 agent 做下一轮决定时看的就是它 —— `node_prepare` 注入的那条 `SystemMessage`。
**为什么要注入**：不注入的话，主 agent 只看得到自己对话历史里那几条工具返回，
**不知道已经派过什么** —— 实测后果就是"用户补一句，它把三个任务全部重跑"（S14）。

## 设计原则（不变量）

1. **只提供事实，不替它做决定** —— "要不要重跑"是理解问题，该柔性。
2. **说事实，不下判决** —— 三态是平台按**结构**算的（交了产物 / 申报要信息 / 都没有），
   标记就照着事实说；"✅ 已完成 / ❌ 失败"是**判定的口吻** ✗（"够不够"由主 agent 判）。〔沿革 5〕
3. **故障标记压过 `stage` 标记** —— 故障的 Task `stage` 也是 `failed`，照 stage 说话就是
   **假话**：那句话的意思是"**执行器**没干成"，而故障是**平台根本没跑成**。〔沿革 8〕
4. **切了必须标** —— 见「关键取舍 ②」。

## 关键取舍

**① 显式截断，不做渐进式披露。** 它是**唯一"故意短"的一跳**，**理由是出处**：台账是
**每轮重复注入的索引**，而全文另有出处 —— 那次的**回执**（`receipt.py`）就在主 agent 的
对话历史里。渐进式披露要配一个"按需取"的工具，这里不需要新造。

⚠️ **待答那一档更进一步：一个字都不重印，只指路**（〔沿革 11〕）—— 因为那一档的全文
出处**不止回执**，还有【待答】，而后者**100% 覆盖**（`node_finalize` 无条件注入）。
原来的"截断到 150 字 ＋ 指向回执"在那里是**多余的一份**：实测每句 `Task.asked` 在主 agent
上下文里出现两遍，而**截断的那份就是它**。

**② 切了不标，是这两种做法里更糟的一种。** 读的人分不清"它就说这么多"还是"被切了" ——
而这两种情况该做的决定**完全不同**（前者该换个说法重派，后者该去翻回执）。

**③ 全文在哪由 `run_by` 决定，不许写死** —— 两条路的出处不一样（见 `_SRC`），
两条答案都**不许现编**：指向一个"存在但内容不对"的出处，比指向不存在的更坏。〔沿革 3〕

## 遗留问题

- **`TaskStage` 暂缺三个状态**（评审人 C1 提过 —— 先记下为什么不做、什么时候该做）：
  - `pending` —— 建 Task 就立刻派发，没有"创建了还没跑"的窗口。等做「计划-执行分离」时再加；
  - `waiting_for_dependency` —— `delegate` 是**同步**的，依赖在主 agent 循环里天然解决
    （它先调 A、拿到产物 ID、再调 B）。等做「异步委派」时再加；
  - `cancelled` —— 用户明确放弃时主动取消。需要给主 agent 新工具，且该场景尚未实测到。
    等真遇到再加。

## 沿革（改过什么、为什么改）

> 编号是**引用锚**（正文里写 `〔沿革 N〕`）—— **只追加、不改号**，新条目加在**末尾**。

1. **「交接三问」的落地**（2026-11-02，用户定）：*"一定要注意交接的地方：① 交接了什么内容
   ② **内容是否被截断了** ③ **过长的交接内容是否考虑了渐进式披露**。"* —— `brief` 那句
   "要短就得说清'这是短的'"就是它。
2. **顶层 import**（2026-11-04 复审 N3）。这里原来是**函数内** import —— 无环，纯习惯：
   `trace` 只依赖 `config`，谁 import 它都不会成环。
3. **`_SRC` 的两条答案**（2026-11-04 复审 E2）。原来对两条路都写"全文见那次的回执" ——
   投递那条路指过去，主 agent 会翻到**上一轮**的回执（内容还是旧的），把旧的当成当前的：
   **指向一个"存在但内容不对"的出处，比指向不存在的更坏**（它会照错的往下判断）。
   ⇒ 两条答案分开，`feed` 那条就说清"你手上没有"；`run_by` 缺失时 fail-safe 到"没有全文"。
4. **待答那档打 `asked`、不打 `report`**（2026-11-04，和 F18 一起改）。`report` 是执行器
   **最后说的那段话**（"好的，第一个问题已发出…"那类过场），而主 agent 需要知道的是
   "**它在等什么**"。这行还有个结构作用：它是**平台的话**（`SystemMessage`），所以主 agent
   不会以为那是自己说过的（那正是 F18 的机制成因）；台账每轮都在最前面 → **答不脱离问**。
5. **`STAGE_MARK` 改成说事实、不下判决**（2026-11-05，判定退休）。原来写的是
   "✅ 已完成 / ❌ 失败" ✗ —— 那是**判定的口吻**；"够不够"由主 agent 判 ✓，
   平台只知道自己看见了什么 ✓。
6. **`progress` / `missing` 两行删掉**（2026-11-05，判定退休）。那两样是**判定吐的**，
   判定那次调用整个没了 → **没有来源了**。`NEEDS_DETAIL` 里的"进度 / 缺失项"同批一起去掉，
   只剩执行器原话（`report`）。
7. **走唯一那条渲染路**（2026-11-05）。在这之前【平台提示】是**就地写的字面量**：段名后面
   **直接跟内容**、续行缩进 **6 格**、结尾那句提示掉在 0 列 —— 和交接书/回执那套"段名 0 列 ·
   段体 2 列 · 每层 +2"**不是一条规矩**（用户定为违反）。段名收进 `SECTION` 之后，
   缩进也改成**相对写**（`render_hop` 会整块缩 2 格）。
8. **平台故障在台账里说真话**（2026-11-05 修 A3）。原来是"同一件事两副面孔"：回执说
   "⚠️ 平台故障，原样再派一次"，台账说"❌ 失败" —— 而主 agent 做下一轮决定时看的**是台账**。
9. **两类故障两种标记**（2026-11-06，外测 SX-07）。`rejected`（4xx）是上游对**这份内容**的
   确定性拒绝 —— "原样再委派"对它就是**错的话**（重发会再被拒）。键 = `FaultKind`（`""` 除外）。
10. **加第三档 `timeout`**（2026-11-06，外审 F9 的墙钟）。它一直在干活、只是没干完 ——
    "原样再委派"成立；但**老超时说明活太大**，多给一句可执行的（拆小）。
11. **待答那档不再重印问题，改成指路**（2026-11-06，用户定：*"这个也要修复啊"*）。
    实测（`tmp/probe_dup.py`，读真会话日志）：每一句 `Task.asked` 在主 agent 上下文里
    出现**两遍** —— 一遍【待答】（`node_finalize` 无条件注入，**全文**），一遍回执或
    **这里**（`brief(q, 150)`，**截断的**）。⇒ 撤**截断的那份**、留全文那份：信息不丢，
    而且撤反了才会丢（`feed` 那条路**没有回执**，台账原本是它唯一的出处）。
    ⚠️ **为什么不是撤【待答】**：`graph.py`〔沿革 21〕已实测"撤掉注入 → `_user_turns` 的
    「它在回答的上一句」退化成主 agent 的旧回复"；而且【待答】是**给用户的那一份**
    （"显示给人的和传给 LLM 的是同一份"）。
    ⚠️ **依据不是推理**：`graph.py`〔沿革 21〕那条实测**已经写着**"问题内容还从**台账和
    回执**进来 —— 只要它知道，它就会写" —— 撤掉这里不会让它"不知道"。
    ⚠️ 段名从 `SECTION` 取，**不写死**（段名只有一处定义）。
"""

from __future__ import annotations

# ⚠️ **顶层 import** —— 这里原来是**函数内** import（纯习惯，不是防环：`trace` 只依赖
# `config`，谁 import 它都不会成环）。〔沿革 2〕
from proto import trace
from proto.handoff import TaskStage, render_hop

#: `Task.stage` 的全部取值 —— **与 `handoff.OutcomeStatus` 前三个同名**。
#: 唯一的映射是 `incomplete → failed`（判定说"还没做完"，推满轮次后任务记"失败"）。
#:
#: ⚠️ **这些是"要管"的状态**；`superseded` 是"不用管了"（同技能被重新委派时自动标记），
#: 所以台账里**不展开细节**，只列一行。另外三个状态（`pending` / `waiting_for_dependency` /
#: `cancelled`）暂未实现 —— 为什么不做、什么时候该做，见模块头「遗留问题」。
#:
#: 键 = `TaskStage`（词汇表）—— 打错键名 mypy 会报；覆盖性由 `unit_handoff` 的守卫盯着（N4）。
#: 🔴 **说事实，不下判决** —— 三态是平台按**结构**算的（交了产物 / 申报要信息 / 都没有），
#: 所以这里也照着事实说；"✅ 已完成 / ❌ 失败" ✗ 是**判定的口吻**（"够不够"由主 agent 判 ✓，
#: 平台只知道自己看见了什么 ✓）。〔沿革 5〕
STAGE_MARK: dict[TaskStage, str] = {
    "running": "⏳ 进行中",
    "completed": "✅ 它交付了产物",
    "waiting_for_input": "⚠️ 它在要信息",
    "failed": "❌ 它没交付、也没说要什么",
    "superseded": "🔁 已被新的委派取代（不用管了）",
}

#: 需要**展开细节**（执行器原话 `report`）的状态 —— 判定退休前还有"进度 / 缺失项"，
#: 同批删了。〔沿革 6〕
NEEDS_DETAIL = ("waiting_for_input", "failed")

#: 🔴 **平台故障那一档的标记 —— 它压过 `stage` 标记**。
#:
#: 故障的 Task `stage` 也是 `failed`，但 `STAGE_MARK["failed"]`（"❌ 它没交付、也没说要什么"）
#: 对平台故障就是**假话** —— 那句话的意思是"**执行器**没干成"，而故障是**平台根本没跑成**，
#: 两者主 agent 该做的事**完全不同**（原样重派 vs 换说法重派 / 向用户说明）。〔沿革 7〕
#:
#: **事实来源是 `Task.fault`**（`absorb_outcome` 写的，一处定义）—— 与回执的
#: 【平台故障】（`DELIVERY["fault"]` / `DELIVERY_FAULT_REJECTED` / `DELIVERY_FAULT_TIMEOUT`）
#: 是**同一个事实的两个视图**（视图可以不一样，事实只能有一处）。
#:
#: 🔴 **一类故障一种标记**：`rejected`（4xx）是上游对**这份内容**的确定性拒绝 ——
#: "原样再委派"对它就是**错的话**（重发会再被拒）。键 = `FaultKind`（`""` 除外）——
#: 覆盖性由 `unit_handoff` ⑬ 的守卫盯着；分类从哪来见 `FaultKind`。
#: ⚠️ 取不到 / 不认识 kind（fixture、旧 Task）→ 回落 `transient`（**同旧行为**，保守）。
#: 〔沿革 9 · 10〕
FAULT_MARK: dict[str, str] = {
    "transient": "⚠️ 平台故障（这一轮**没跑成** —— 原样再委派一次即可）",
    "rejected": "⚠️ 上游**拒绝了这次请求**（原样重发会再被拒 —— **换措辞/改内容**再委派）",
    # 🔴 **第三种故障**：它一直在干活、只是没干完 —— 所以"原样再委派"成立；
    #    但**老超时说明活太大**，多给一句可执行的（拆小）。〔沿革 10〕
    "timeout": "⚠️ **时间用完了**（这一趟没跑完就被叫停 —— 原样再委派可以；"
               "**老超时就说明活太大**，拆小一点再委派）",
}


#: 台账截断时"全文在哪"的两种答案 —— **由这一轮是谁起的决定**（`Task.run_by`）：
#:
#: - `delegate`：全文在**那次的回执**里（主 agent 自己的工具返回，就在它上下文里）；
#: - `feed`：**没有回执** —— 那轮是用户答复后**平台**直接调 `run_task` 重跑的，
#:   全文压根不在主 agent 上下文里（它只有台账里这 150 字）。
#:
#: 🔴 两条答案都**不许现编**：`feed` 那条就说清"你手上没有"，同判定那处"它没有读全文的手段"。
#: （原来对两条路都写"全文见那次的回执"—— 指错了比指不到更坏，见〔沿革 3〕。）
_SRC = {
    "delegate": "全文见那次的回执（`delegate` 的返回）",
    "feed": "全文**不在你的上下文里** —— 这轮是平台投递你的答复后重跑的，没有回执",
}
#: `run_by` 缺失（比如 `case.initial_tasks` 注入的 Task）时的默认 —— **fail-safe 到"没有全文"**：
#: 说不准就别指向一个出处（指错了比指不到坏）。
_SRC_DEFAULT = "全文**不在你的上下文里**"


def brief(text: str, limit: int, what: str = "长文本", *, run_by: str = "") -> str:
    """台账里的长文本 —— **要短就得说清"这是短的"**（用户的「交接三问」〔沿革 1〕）。

    > "一定要注意交接的地方：① 交接了什么内容 ② **内容是否被截断了**
    >  ③ **过长的交接内容是否考虑了渐进式披露**。"

    **为什么是显式截断、不是渐进式披露**，以及**切了不标为什么更糟** ——
    两条都在模块头「关键取舍」（① ／ ②），这里不重开。

    ⚠️ 全文在哪**两条路不一样**（见 `_SRC`），由 `run_by` 决定，不能写死。
    ⚠️ 顺手把换行压成空格：台账是**一行一条**的列表，多行值会把缩进结构撑坏。
    这不算内容损失（只动了空白），但**别在这里做别的加工**。
    """
    text = " ".join(str(text or "").split())
    if len(text) <= limit:
        return text
    # 🔴 **切了一刀就报一刀**（判据②：主动截断要有显式标记 + 说清全文在哪）。
    # 标记在**文本里**（读的人看得见），这一行在**日志里**（复盘的人看得见）—— 两者都要。
    src = _SRC.get(run_by, _SRC_DEFAULT)
    trace.cut(f"台账·{what}", limit, len(text), see=src)
    return f"{text[:limit]}……【平台截断：还有 {len(text) - limit} 字，{src}】……"


def render_ledger(tasks: list[dict]) -> str:
    """把 Task 列表渲染成**给主 agent 的台账**（`node_prepare` 注入的那条 SystemMessage）。

    ⚠️ 调用方保证 `tasks` 非空（空的时候 `node_prepare` 直接不注入 —— 闲聊轮次里没有这段）。

    ⚠️ **走唯一那条渲染路**（`render_hop`）—— 段名【平台提示】登记在 `SECTION` 里；
    在这之前它是就地写的字面量，和交接书/回执那套体例**不是一条规矩**（用户定为违反）。〔沿革 7〕
    """
    # ⚠️ **缩进一律相对写**（下面这些行会被 `render_hop` 整块缩 2 格）——
    #    原来这里是**绝对**的（续行手写 6 格、结尾那句提示掉在 0 列）。〔沿革 7〕
    body: list[str] = [f"你已委派出去的工作（共 {len(tasks)} 项）："]
    for t in tasks:
        # 🔴 **平台故障压过 stage 标记**（见 `FAULT_MARK`）：故障的 stage 也是 `failed`，
        #    照 stage 说话就是假话。标记**按故障的类选**（`rejected` 说"换措辞"，
        #    不是"原样再派"）—— 取不到 kind 回落 `transient`（同旧行为，保守）。
        faulted = bool(t.get("fault"))
        mark = (FAULT_MARK.get(str(t.get("fault_kind") or ""), FAULT_MARK["transient"])
                if faulted
                else STAGE_MARK.get(t.get("stage", ""), t.get("stage", "?")))
        arts = f" → {', '.join(t['artifacts'])}" if t.get("artifacts") else ""
        body.append(f"- {t['id']}  「{t['skill']}」  {mark}{arts}")
        # ⚠️ 没完成的任务，把**执行器原话**也带上（信息交接原则）——
        #    只说"没完成"，主 agent 没法决定是换个说法重派、还是向用户说明。
        # ⚠️ `run_by` 一路传下去：这两段**都来自同一轮**，全文在不在主 agent 上下文里
        #    是同一件事（见 `brief` 的 `_SRC`）。
        by = str(t.get("run_by") or "")
        if faulted:
            # 🔴 **故障时打故障原因，不打「执行器说」**：它一个字都没说 ——
            #    照打就是一行"执行器说："后面**空白**（冒号后面什么都没有），
            #    读的人还以为它说了句空话。同一条 `brief` 规矩（长了显式截断＋指向出处）。
            body.append(f"  - 平台故障：{brief(t['fault'], 150, '平台故障', run_by=by)}")
        elif t.get("stage") == "waiting_for_input":
            # 🔴 **不重印问题**〔沿革 11〕。那行原来是**第三份**：实测
            #    （`tmp/probe_dup.py`）每一句 `Task.asked` 在主 agent 上下文里出现**两遍**
            #    —— 一遍【待答】、一遍回执或这里。而【待答】是**唯一 100% 覆盖**的那份
            #    （`node_finalize` 无条件注入）**且是全文**；这行是 `brief(q, 150)`，
            #    **截断的**。⇒ 撤**截断的那份**、留全文那份，信息不丢；**撤反了才丢**
            #    （`feed` 那条路上没有回执）。〔沿革 11〕
            #    ⚠️ **待答那档打 `asked`、不打 `report`** 这条不变：`report` 是执行器最后
            #    说的那段过场，而主 agent 需要知道的是"**它在等什么**"。
            #    ⚠️ **结构作用保住**：它还是**平台的话**（`SystemMessage`）、还在每轮最前面
            #    —— "答不脱离问"靠"知道它在等什么 ＋ 去哪儿看"仍然成立〔沿革 4〕。
            #    ⚠️ 依据：`graph.py`〔沿革 21〕已实测过"问题内容还从**台账和回执**进来"
            #    —— 撤掉这里**不会**让它"不知道"。
            #    🔴 **不许点名那个段名**（写死 `【待答】` 是第二份定义；读 `SECTION['relay']`
            #    也不行 —— `SECTION[...]` 只许出现在 `render_hop(...)` 调用里，
            #    守卫 `unit_handoff_form` ⑤' 会红）。**描述，不点名**：
            #    "平台已原样转达" 已经说清它在哪、是谁的话。
            q = str(t.get("asked") or "").strip()
            if q:
                body.append(f"  - 它要的信息：（{len(q)} 字，**平台已原样转达**，此处不重贴）")
            else:
                # ⚠️ **不许留一个冒号后面空白**（同上面故障那档的理由）—— 说清是"没有"。
                body.append("  - 它要的信息：（**这一条没留下问题原话**）")
        elif t.get("stage") in NEEDS_DETAIL:
            # ⚠️ 原来这里还有"已做到（判定说）/ 还缺（判定说）"两行 —— 随判定退休一起删了
            #    （`Task.progress` / `Task.missing` 没有来源）。〔沿革 6〕
            body.append(f"  - 执行器说：{brief(t['report'], 150, '执行器说', run_by=by)}")

    waiting = [t for t in tasks if t.get("stage") == "waiting_for_input"]
    # ⚠️ 这里**不再**叫主 agent 去重新委派 —— 待答的投递和转达都由平台做（见 `_feed_waiting`
    #    和 `node_finalize`）。主 agent 只需要别自己替用户编一个答案。
    body.append(
        "**「在要信息」的那些，平台已经负责把问题转达给用户、也会把用户的答复投回去** ——"
        "你**不用**重新委派它们，更不要自己替用户编一个答案。"
        if waiting
        else "（用户补充信息时，**只重跑受影响的任务**，已完成且不受影响的不动。）"
    )
    # 🔴 **走唯一那条渲染路**：段名【平台提示】登记在 `SECTION` 里，不许就地拼字符串。〔沿革 7〕
    return render_hop("ledger", {"ledger": "\n".join(body)})
