"""**台账**（平台 → 主 agent）：每轮开头把"派过什么、干到哪了"摆到它面前。

**只提供事实，不替它做决定**（"要不要重跑"是理解问题，该柔性）。

为什么要注入：不注入的话，主 agent 只看得到自己对话历史里那几条工具返回，
**不知道已经派过什么** —— 实测后果就是"用户补一句，它把三个任务全部重跑"（S14）。

🔴 **它是唯一"故意短"的一跳**：台账是**每轮重复注入的索引**，而全文另有出处 ——
那次的**回执**（`receipt.py`）就在对话历史里。所以这里选**显式截断**而不是渐进式披露
（渐进式披露要配一个"按需取"的工具，这里不需要新造）。

> **切了不标，是这两种做法里更糟的一种**：读的人分不清"它就说这么多"还是"被切了" ——
> 而这两种情况该做的决定**完全不同**。
"""

from __future__ import annotations

# ⚠️ 顶层 import（2026-11-04 复审 N3）：这里原来是**函数内** import —— 无环，纯习惯。
# `trace` 只依赖 `config`，谁 import 它都不会成环。
from proto import trace
from proto.handoff import TaskStage

#: `Task.stage` 的全部取值 —— **与 `handoff.OutcomeStatus` 前三个同名**。
#: 唯一的映射是 `incomplete → failed`（判定说"还没做完"，推满轮次后任务记"失败"）。
#:
#: ⚠️ **这些是"要管"的状态**；`superseded` 是"不用管了"（同技能被重新委派时自动标记），
#: 所以台账里**不展开细节**，只列一行。
#:
#: 暂未实现的三个（评审人 C1 提过，先记下为什么不做、什么时候该做）：
#:   - `pending`                —— 建 Task 就立刻派发，没有"创建了还没跑"的窗口。
#:                                 等做「计划-执行分离」时再加
#:   - `waiting_for_dependency` —— `delegate` 是**同步**的，依赖在主 agent 循环里天然解决
#:                                 （它先调 A、拿到产物 ID、再调 B）。等做「异步委派」时再加
#:   - `cancelled`              —— 用户明确放弃时主动取消。需要给主 agent 新工具，
#:                                 且该场景尚未实测到。等真遇到再加
#: 键 = `TaskStage`（词汇表）—— 打错键名 mypy 会报；覆盖性由 `unit_handoff` 的守卫盯着（N4）。
#: 🔴 **说事实，不下判决**（2026-11-05，判定退休）：三态是平台按**结构**算的
#: （交了产物 / 申报要信息 / 都没有）—— 所以这里也照着事实说。
#: 原来写的是"✅ 已完成 / ❌ 失败" ✗ —— 那是**判定的口吻**（"够不够"由主 agent 判 ✓），
#: 平台只知道自己看见了什么 ✓。
STAGE_MARK: dict[TaskStage, str] = {
    "running": "⏳ 进行中",
    "completed": "✅ 它交付了产物",
    "waiting_for_input": "⚠️ 它在要信息",
    "failed": "❌ 它没交付、也没说要什么",
    "superseded": "🔁 已被新的委派取代（不用管了）",
}

#: 需要**展开细节**（进度 / 缺失项 / 执行器原话）的状态
NEEDS_DETAIL = ("waiting_for_input", "failed")

#: 🔴 **平台故障那一档的标记 —— 它压过 `stage` 标记**（2026-11-05 修 A3）。
#:
#: 故障的 Task `stage` 也是 `failed`，但 `STAGE_MARK["failed"]`（"❌ 它没交付、也没说要什么"）
#: 对平台故障就是**假话** —— 那句话的意思是"**执行器**没干成"，而故障是**平台根本没跑成**，
#: 两者主 agent 该做的事**完全不同**（原样重派 vs 换说法重派 / 向用户说明）。
#: 原来是"同一件事两副面孔"：回执说"⚠️ 平台故障，原样再派一次"，台账说"❌ 失败" ——
#: 而主 agent 做下一轮决定时看的**是台账**。
#:
#: **事实来源是 `Task.fault`**（`absorb_outcome` 写的，一处定义）—— 与回执的
#: 【平台故障】（`DELIVERY["fault"]`）是**同一个事实的两个视图**（视图可以不一样，
#: 事实只能有一处）。
FAULT_MARK = "⚠️ 平台故障（这一轮**没跑成** —— 原样再派一次即可）"


#: 台账截断时"全文在哪"的两种答案 —— **由这一轮是谁起的决定**（`Task.run_by`）：
#:
#: - `delegate`：全文在**那次的回执**里（主 agent 自己的工具返回，就在它上下文里）；
#: - `feed`：**没有回执** —— 那轮是用户答复后**平台**直接调 `run_task` 重跑的，
#:   全文压根不在主 agent 上下文里（它只有台账里这 150 字）。
#:
#: 🔴 **2026-11-04 复审 E2**：原来对两条路都写"全文见那次的回执"。投递那条路指过去，
#: 主 agent 会翻到**上一轮**的回执（内容还是旧的），把旧的当成当前的 ——
#: **指向一个"存在但内容不对"的出处，比指向不存在的更坏**（它会照错的往下判断）。
#: 两条答案都不许现编：`feed` 那条就说清"你手上没有"，同判定那处"它没有读全文的手段"。
_SRC = {
    "delegate": "全文见那次的回执（`delegate` 的返回）",
    "feed": "全文**不在你的上下文里** —— 这轮是平台投递你的答复后重跑的，没有回执",
}
#: `run_by` 缺失（比如 `case.initial_tasks` 注入的 Task）时的默认 —— **fail-safe 到"没有全文"**：
#: 说不准就别指向一个出处（指错了比指不到坏）。
_SRC_DEFAULT = "全文**不在你的上下文里**"


def brief(text: str, limit: int, what: str = "长文本", *, run_by: str = "") -> str:
    """台账里的长文本 —— **要短就得说清"这是短的"**（用户 2026-11-02 的「交接三问」）。

    > "一定要注意交接的地方：① 交接了什么内容 ② **内容是否被截断了**
    >  ③ **过长的交接内容是否考虑了渐进式披露**。"

    这里选**显式截断**而不是渐进式披露，理由是**出处**：台账是**每轮重复注入**的索引，
    而全文另有出处（在哪见 `_SRC` —— **两条路不一样**，所以由 `run_by` 决定，
    不能写死）。渐进式披露要配一个"按需取"的工具，这里不需要新造。

    🔴 **切了不标，是这两种做法里更糟的一种**：读的人分不清
    "它就说这么多"还是"被切了" —— 而这两种情况该做的决定**完全不同**
    （前者该换个说法重派，后者该去翻回执）。

    ⚠️ 顺手把换行压成空格：台账是**一行一条**的列表，多行值会把缩进结构撑坏。
    这不算内容损失（只动了空白），但**别在这里做别的加工**。
    """
    text = " ".join(str(text or "").split())
    if len(text) <= limit:
        return text
    # 🔴 **切了一刀就报一刀**（判据②：主动截断要有显式标记 + 说清全文在哪）。
    # 标记在**文本里**（读的人看得见），这一行在**日志里**（复盘的人看得见）—— 两者都要。
    src = _SRC.get(run_by, _SRC_DEFAULT)
    trace.cut(f"台账·{what}", limit, len(text), see=src)
    return f"{text[:limit]}……【平台截断：还有 {len(text) - limit} 字，{src}】……"


def render_ledger(tasks: list[dict]) -> str:
    """把 Task 列表渲染成**给主 agent 的台账**（`node_prepare` 注入的那条 SystemMessage）。

    ⚠️ 调用方保证 `tasks` 非空（空的时候 `node_prepare` 直接不注入 —— 闲聊轮次里没有这段）。
    """
    lines: list[str] = []
    for t in tasks:
        # 🔴 **平台故障压过 stage 标记**（见 `FAULT_MARK`）：故障的 stage 也是 `failed`，
        #    照 stage 说话就是假话。
        faulted = bool(t.get("fault"))
        mark = (FAULT_MARK if faulted
                else STAGE_MARK.get(t.get("stage", ""), t.get("stage", "?")))
        arts = f" → {', '.join(t['artifacts'])}" if t.get("artifacts") else ""
        lines.append(f"- {t['id']}  「{t['skill']}」  {mark}{arts}")
        # ⚠️ 没完成的任务，把**进度 / 缺失项**也带上（信息交接原则）——
        #    只说"没完成"，主 agent 没法决定是换个说法重派、还是向用户说明。
        # ⚠️ `run_by` 一路传下去：这两段**都来自同一轮**，全文在不在主 agent 上下文里
        #    是同一件事（见 `brief` 的 `_SRC`）。
        by = str(t.get("run_by") or "")
        if faulted:
            # 🔴 **故障时打故障原因，不打「执行器说」**：它一个字都没说 ——
            #    照打就是一行"执行器说："后面**空白**（冒号后面什么都没有），
            #    读的人还以为它说了句空话。同一条 `brief` 规矩（长了显式截断＋指向出处）。
            lines.append(f"      平台故障：{brief(t['fault'], 150, '平台故障', run_by=by)}")
        elif t.get("stage") in NEEDS_DETAIL:
            # ⚠️ 原来这里还有"已做到（判定说）/ 还缺（判定说）"两行 —— 判定退休后
            #    `Task.progress` / `Task.missing` 没有来源了，两行一起删（2026-11-05）。
            lines.append(f"      执行器说：{brief(t['report'], 150, '执行器说', run_by=by)}")

    waiting = [t for t in tasks if t.get("stage") == "waiting_for_input"]
    # ⚠️ 这里**不再**叫主 agent 去重新委派 —— 待答的投递和转达都由平台做（见 `_feed_waiting`
    #    和 `node_finalize`）。主 agent 只需要别自己替用户编一个答案。
    hint = (
        "\n\n**「等用户答复」的那些，平台已经负责把问题转达给用户、也会把用户的答复投回去** ——"
        "你**不用**重新委派它们，更不要自己替用户编一个答案。"
        if waiting
        else "\n\n（用户补充信息时，**只重跑受影响的任务**，已完成且不受影响的不动。）"
    )
    return f"【平台提示】你已委派出去的工作（共 {len(tasks)} 项）：\n" + "\n".join(lines) + hint
