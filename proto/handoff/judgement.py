"""**判定**（平台 → 判定 → 平台）：输入模板 ＋ 输出 schema。

> 判定是**软判断**：它的效果**完全取决于喂给它的上下文**（用户原则）。
> 所以"喂什么、怎么截"必须和 schema 放在一起 —— 见 `proto/handoff/__init__.py` 的组织方式。

⚠️ 判定**没有工具循环**：它只看得见这里的 prompt，取不了全文 ——
所以截断**必须显式标注**，否则它会基于不完整的信息**自信地下判断**
（那比"猜"更糟，是"以为自己没在猜"）。

⚠️ 本模块**只放 schema 与模板**，`safe_structured` 那次调用在 `proto/executor.py`
（那是编排，不是交接内容）。
"""

